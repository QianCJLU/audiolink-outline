public sealed class AudioLinkOutlineLitePlugin : Plugin<AudioLinkOutlineLitePlugin>
{
    public override string QualifiedName=>"audiolink-outline-lite";
    public override string DisplayName=>"audiolink outline lite";
    protected override void Configure()
    {
        InPhase(BuildPhase.Resolving).BeforePlugin("nadena.dev.modular-avatar").Run("Upgrade audiolink outline lite Parameters",ctx=>{
            foreach(var settings in ctx.AvatarRootObject.GetComponentsInChildren<AudioLinkOutlineLiteSettings>(true))
            {
                if(!settings.installationConfirmed){
                    foreach(var component in settings.GetComponents<Component>().Where(c=>c is nadena.dev.modular_avatar.core.ModularAvatarMenuInstaller||c is nadena.dev.modular_avatar.core.ModularAvatarParameters||c is nadena.dev.modular_avatar.core.ModularAvatarMergeAnimator).ToArray())UnityEngine.Object.DestroyImmediate(component);
                    continue;
                }
                var parameters=settings.GetComponent<nadena.dev.modular_avatar.core.ModularAvatarParameters>();
                if(!parameters)continue;
                AudioLinkOutlineLiteInstaller.ConfigureParameters(parameters,settings);
            }
        });
        InPhase(BuildPhase.Optimizing).AfterPlugin("nadena.dev.modular-avatar").BeforePlugin("com.anatawa12.avatar-optimizer").Run("Build audiolink outline lite",ctx=>{
            var settings=ctx.AvatarRootObject.GetComponentsInChildren<AudioLinkOutlineLiteSettings>(true).Where(s=>s.enabled&&s.installationConfirmed&&s.gameObject.activeInHierarchy).ToArray();
            if(settings.Length>1)throw new InvalidOperationException("同一角色只能安装一份音律轮廓，请移除重复的 audiolink outline lite 对象。");
            foreach(var s in settings)
            {if(EditorUserBuildSettings.activeBuildTarget!=BuildTarget.Android)AudioLinkOutlineLiteBuild.Apply(s);UnityEngine.Object.DestroyImmediate(s);}
            foreach(var s in ctx.AvatarRootObject.GetComponentsInChildren<AudioLinkOutlineLiteSettings>(true))UnityEngine.Object.DestroyImmediate(s);
        });
    }
}
public static class AudioLinkOutlineLiteBuild
{
    public const string ChildName="__ALOLiteOutline";
    public const string ModeParameter="ALOLite/Breath";
    public const string ToggleParameter="ALOLite/Enabled";
    public static bool Selected(SkinnedMeshRenderer r,Transform root,AudioLinkOutlineLiteSettings settings)
    {
        if(r.name==ChildName||r.name=="__ALOLiteMask"||r.sharedMaterials.Length==0)return false;
        // Follow only the opaque output generated by SeeThroughHair for a renderer
        // explicitly selected by the user. Never include other descendants by name.
        return settings.renderers.Any(selected=>selected&&(r==selected||
            (r.transform.parent==selected.transform&&r.name==selected.name+" (Transparent)")));
    }
    public static void Apply(AudioLinkOutlineLiteSettings s)
    {
        var avatar=s.GetComponentInParent<VRCAvatarDescriptor>();if(!avatar)throw new Exception("音律轮廓必须放在 Avatar Descriptor 的子物体中。");var root=avatar.transform;
        if(avatar.GetComponentsInChildren<Component>(true).Any(c=>c&&c.GetType().FullName=="AudioLinkOutline.AudioLinkOutlineSettings"))throw new Exception("请先从当前角色移除完整版预制件，再安装轻量版。同一角色使用一套轮廓配置。");
        if(avatar.GetComponentsInChildren<Component>(true).Any(c=>c&&c.GetType().Name=="PlumAudioOutline"))throw new Exception("角色已有旧版 Plum 轮廓，请先移除旧轮廓配置，再安装通用版。");
        if(!s.outline)throw new Exception("缺少音律轮廓材质，请在 Inspector 中点击‘一键应用安装/修复’。");
        if(s.renderers==null||s.renderers.Length==0)throw new Exception("尚未选择描边部件。请选中音律轮廓配置，勾选需要的部件后再构建。");
        if(s.renderers.Any(r=>!r||!r.transform.IsChildOf(root)))throw new Exception("描边列表含已删除或其他角色的部件，请重新选择。");
        int stencil=s.stencilBit;if(stencil<1||stencil>128||(stencil&(stencil-1))!=0)throw new Exception("Stencil 位必须是 1/2/4/8/16/32/64/128。");
        var fx=avatar.baseAnimationLayers.Single(l=>l.type==VRCAvatarDescriptor.AnimLayerType.FX).animatorController as AnimatorController;
        if(!fx)throw new Exception("MA 未生成 FX 控制器，请一键应用安装/修复（MA Merge Animator）。");
        var defaults=fx.parameters;
        for(int i=0;i<defaults.Length;i++) {
            if(defaults[i].name==ToggleParameter)defaults[i].defaultBool=s.defaultOn;
            if(defaults[i].name==ModeParameter)defaults[i].defaultBool=s.defaultBreathing;
        }
        fx.parameters=defaults;
        if(fx.layers.Any(l=>l.name.StartsWith("ALO Outline ")))throw new Exception("重复生成音律轮廓层。");
        var originalStates=fx.layers.SelectMany(l=>States(l.stateMachine)).ToArray();
        bool writeDefaults=originalStates.Length==0||originalStates.Count(st=>st.writeDefaultValues)>=originalStates.Length/2f;
        var motions=new Dictionary<Motion,Motion>();foreach(var l in fx.layers)CloneMotions(l.stateMachine,motions);
        var clips=fx.animationClips.Distinct().ToArray();
        var stencilMaterials=avatar.GetComponentsInChildren<Renderer>(true).SelectMany(r=>r.sharedMaterials)
            .Concat(clips.SelectMany(c=>AnimationUtility.GetObjectReferenceCurveBindings(c).SelectMany(b=>AnimationUtility.GetObjectReferenceCurve(c,b))).Select(k=>k.value as Material));
        stencil=AudioLinkOutlineLiteStencil.Select(s.stencilBit,stencilMaterials,clips);
        if(stencil!=s.stencilBit)Debug.Log("audiolink outline lite: preferred stencil bit "+s.stencilBit+" is occupied; automatically using "+stencil+" without changing original face/hair stencil values.");
        var targets=avatar.GetComponentsInChildren<SkinnedMeshRenderer>(true).Where(r=>r.sharedMesh&&Selected(r,root,s)&&AudioLinkOutlineLiteMesh.Indices(r).Length>0).ToArray();
        if(targets.Length==0)throw new Exception("所选部件没有可生成轮廓的三角面蒙皮网格。");
        // Write only a reserved stencil bit in the existing opaque character draw.
        // No body shader files, texture assets or full-resolution geometry are added.
        var guards=new Dictionary<Material,Material>();
        foreach(var r in avatar.GetComponentsInChildren<Renderer>(true))r.sharedMaterials=r.sharedMaterials.Select(m=>Guard(m,guards,stencil)).ToArray();
        foreach(var clip in clips)foreach(var b in AnimationUtility.GetObjectReferenceCurveBindings(clip))
        {
            var keys=AnimationUtility.GetObjectReferenceCurve(clip,b);bool changed=false;
            for(int i=0;i<keys.Length;i++)if(keys[i].value is Material m){keys[i].value=Guard(m,guards,stencil);changed=true;}
            if(changed)AnimationUtility.SetObjectReferenceCurve(clip,b,keys);
        }
        float bottom=float.PositiveInfinity,top=float.NegativeInfinity;
        foreach(var r in targets)
        {
            var baked=new Mesh();r.BakeMesh(baked);
            foreach(var v in baked.vertices){float y=root.InverseTransformPoint(r.transform.TransformPoint(v)).y;bottom=Mathf.Min(bottom,y);top=Mathf.Max(top,y);}
            UnityEngine.Object.DestroyImmediate(baked);
        }
        // Independent alpha-aware masks permit shaders without writable stencil properties.
        // Mask and shell share reduced geometry; both draws count toward the budget.
        var autoMode=new AnimationClip{name="Automatic audio response"};var breathMode=new AnimationClip{name="Fixed breathing"};
        var visibleClip=new AnimationClip{name="Outline renderers awake"};var hiddenClip=new AnimationClip{name="Outline renderers asleep"};
        var scaleLow=new AnimationClip{name="Outline scale zero"};var scaleHigh=new AnimationClip{name="Outline scale upper"};
        int budget=Mathf.Clamp(s.shellTriangleBudget,AudioLinkOutlineLiteSettings.MinimumTriangleBudget,AudioLinkOutlineLiteSettings.MaximumTriangleBudget);
        var capacities=targets.Select(r=>AudioLinkOutlineLiteMesh.Indices(r).Length/3).ToArray();
        var desired=targets.Select((r,i)=>Mathf.Sqrt(capacities[i])*(r==avatar.VisemeSkinnedMesh?1.3f:1)).ToArray();
        var budgets=new int[targets.Length];int remaining=budget/2;
        // Water-fill: small parts may retain full detail; unused allocation moves
        // to larger surfaces instead of leaving most of the user's budget idle.
        for(int round=0;round<targets.Length+2&&remaining>0;round++)
        {
            var active=Enumerable.Range(0,targets.Length).Where(i=>budgets[i]<capacities[i]).ToArray();if(active.Length==0)break;
            float sum=active.Sum(i=>desired[i]);int available=remaining;
            foreach(int i in active){int add=Math.Min(remaining,Math.Min(capacities[i]-budgets[i],Math.Max(1,Mathf.FloorToInt(available*desired[i]/sum))));budgets[i]+=add;remaining-=add;}
        }
        int added=0;long memory=0;
        for(int index=0;index<targets.Length;index++)
        {
            var source=targets[index];string p=AnimationUtility.CalculateTransformPath(source.transform,root);
            var shapes=new HashSet<string>(clips.SelectMany(AnimationUtility.GetCurveBindings).Where(b=>b.path==p&&b.type==typeof(SkinnedMeshRenderer)&&b.propertyName.StartsWith("blendShape.")).Select(b=>b.propertyName.Substring(11)));
            {
                foreach(string name in shapes.ToArray())
                {
                    int shape=source.sharedMesh.GetBlendShapeIndex(name);if(shape<0){shapes.Remove(name);continue;}
                    float initial=source.GetBlendShapeWeight(shape);
                    if(initial!=0)continue; // Preserve the simplifier's exact original vertex positions.
                    var binding=EditorCurveBinding.FloatCurve(p,typeof(SkinnedMeshRenderer),"blendShape."+name);
                    var curves=clips.Select(c=>AnimationUtility.GetEditorCurve(c,binding)).Where(c=>c!=null).ToArray();
                    // Keep every moving/overshooting curve. A shape that is only
                    // ever assigned its serialized default has no runtime degrees
                    // of freedom, including WD returns, so bake that exact default.
                    if(curves.Length>0&&curves.All(c=>c.keys.All(k=>k.value==initial&&
                        (k.inTangent==0||float.IsInfinity(k.inTangent))&&(k.outTangent==0||float.IsInfinity(k.outTangent)))))shapes.Remove(name);
                }
            }
            // Voice/eyelid shapes are SDK driven, not Animator curves. Mouth detail
            // is small on a silhouette; retain eyelids and viseme shapes for parity.
            if(source==avatar.VisemeSkinnedMesh&&avatar.VisemeBlendShapes!=null)foreach(string name in avatar.VisemeBlendShapes)if(!string.IsNullOrEmpty(name))shapes.Add(name);
            var mesh=AudioLinkOutlineLiteMesh.Create(source,budgets[index],shapes,out var bones);if(!mesh)continue;
            var go=new GameObject(ChildName);go.transform.SetParent(source.transform,false);go.SetActive(s.defaultOn);
            var shell=go.AddComponent<SkinnedMeshRenderer>();shell.sharedMesh=mesh;shell.bones=bones;shell.rootBone=root;shell.sharedMaterials=Enumerable.Range(0,mesh.subMeshCount).Select(slot=>{
                var original=slot<source.sharedMaterials.Length?source.sharedMaterials[slot]:null;
                var m=AudioLinkOutlineLiteSurface.Create(original,s.outline,stencil,false);
                ApplySettings(m,s);m.SetFloat("_ALOBottom",bottom);m.SetFloat("_ALOHeight",top-bottom);m.SetFloat("_ALOBaseScale",Mathf.Abs(root.lossyScale.y));m.SetFloat("_ALOAvatarScale",1);return m;
            }).ToArray();shell.enabled=source.enabled;
            shell.shadowCastingMode=ShadowCastingMode.Off;shell.receiveShadows=false;shell.lightProbeUsage=LightProbeUsage.BlendProbes;shell.probeAnchor=source.probeAnchor;shell.reflectionProbeUsage=ReflectionProbeUsage.Off;
            var bounds=new Bounds(root.InverseTransformPoint(source.bounds.center),Vector3.zero);
            for(int c=0;c<8;c++)bounds.Encapsulate(root.InverseTransformPoint(source.bounds.center+Vector3.Scale(source.bounds.extents,new Vector3((c&1)==0?-1:1,(c&2)==0?-1:1,(c&4)==0?-1:1))));
            bounds.Expand(0.30f+2*(top-bottom)*0.05f);shell.localBounds=bounds;
            for(int i=0;i<mesh.blendShapeCount;i++)shell.SetBlendShapeWeight(i,source.GetBlendShapeWeight(source.sharedMesh.GetBlendShapeIndex(mesh.GetBlendShapeName(i))));
            foreach(var physics in avatar.GetComponentsInChildren<VRC.SDK3.Dynamics.PhysBone.Components.VRCPhysBone>(true))
            {
                var physicsRoot=physics.rootTransform?physics.rootTransform:physics.transform;
                if(go.transform.IsChildOf(physicsRoot)){if(physics.ignoreTransforms==null)physics.ignoreTransforms=new List<Transform>();physics.ignoreTransforms.Add(go.transform);}
            }
            string shellPath=AnimationUtility.CalculateTransformPath(shell.transform,root);
            {
                var active=EditorCurveBinding.FloatCurve(shellPath,typeof(GameObject),"m_IsActive");
                AnimationUtility.SetEditorCurve(visibleClip,active,AnimationCurve.Constant(0,1,1));
                AnimationUtility.SetEditorCurve(hiddenClip,active,AnimationCurve.Constant(0,1,0));
            }
            foreach(var clip in clips)foreach(var b in AnimationUtility.GetCurveBindings(clip).Where(b=>b.path==p&&b.type==typeof(SkinnedMeshRenderer)&&(b.propertyName=="m_Enabled"||(b.propertyName.StartsWith("blendShape.")&&mesh.GetBlendShapeIndex(b.propertyName.Substring(11))>=0))))
            {var copy=b;copy.path=shellPath;AnimationUtility.SetEditorCurve(clip,copy,AnimationUtility.GetEditorCurve(clip,b));}
            AnimationUtility.SetEditorCurve(visibleClip,EditorCurveBinding.FloatCurve(shellPath,typeof(SkinnedMeshRenderer),"material._ALOOn"),AnimationCurve.Constant(0,1,1));
            AnimationUtility.SetEditorCurve(hiddenClip,EditorCurveBinding.FloatCurve(shellPath,typeof(SkinnedMeshRenderer),"material._ALOOn"),AnimationCurve.Constant(0,1,0));
            var modeBinding=EditorCurveBinding.FloatCurve(shellPath,typeof(SkinnedMeshRenderer),"material._ALOBreath");
            AnimationUtility.SetEditorCurve(autoMode,modeBinding,AnimationCurve.Constant(0,1,0));AnimationUtility.SetEditorCurve(breathMode,modeBinding,AnimationCurve.Constant(0,1,1));
            var sb=EditorCurveBinding.FloatCurve(shellPath,typeof(SkinnedMeshRenderer),"material._ALOAvatarScale");
            AnimationUtility.SetEditorCurve(scaleLow,sb,AnimationCurve.Constant(0,1,0));AnimationUtility.SetEditorCurve(scaleHigh,sb,AnimationCurve.Constant(0,1,1000));
            // Copy renderer settings, skin and all newly authored curves to the mask.
            var maskGo=UnityEngine.Object.Instantiate(go,source.transform);maskGo.name="__ALOLiteMask";
            var mask=maskGo.GetComponent<SkinnedMeshRenderer>();
            mask.sharedMaterials=Enumerable.Range(0,mesh.subMeshCount).Select(slot=>{
                var original=slot<source.sharedMaterials.Length?source.sharedMaterials[slot]:null;
                return AudioLinkOutlineLiteSurface.Create(original,s.outline,stencil,true);
            }).ToArray();
            string maskPath=AnimationUtility.CalculateTransformPath(mask.transform,root);
            foreach(var clip in clips.Concat(new[]{visibleClip,hiddenClip}))foreach(var binding in AnimationUtility.GetCurveBindings(clip).Where(b=>b.path==shellPath))
            {var copy=binding;copy.path=maskPath;AnimationUtility.SetEditorCurve(clip,copy,AnimationUtility.GetEditorCurve(clip,binding));}
            foreach(var physics in avatar.GetComponentsInChildren<VRC.SDK3.Dynamics.PhysBone.Components.VRCPhysBone>(true))
            {var physicsRoot=physics.rootTransform?physics.rootTransform:physics.transform;if(maskGo.transform.IsChildOf(physicsRoot))physics.ignoreTransforms.Add(maskGo.transform);}
            added+=2*mesh.triangles.Length/3;memory+=UnityEngine.Profiling.Profiler.GetRuntimeMemorySizeLong(mesh);
        }
        if(added>AudioLinkOutlineLiteSettings.MaximumTriangleBudget||added>budget)throw new Exception("Outline triangle budget exceeded: "+added);
        if(!fx.parameters.Any(p=>p.name=="ScaleFactor"))fx.AddParameter(new AnimatorControllerParameter{name="ScaleFactor",type=AnimatorControllerParameterType.Float,defaultFloat=1});
        var tree=new BlendTree{name="Outline scale",blendType=BlendTreeType.Simple1D,blendParameter="ScaleFactor",useAutomaticThresholds=false};tree.AddChild(scaleLow,0);tree.AddChild(scaleHigh,1000);
        var sm=new AnimatorStateMachine{name="ALO Outline Scale"};var st=sm.AddState("Scale");st.motion=tree;st.writeDefaultValues=true;sm.defaultState=st;fx.AddLayer(new AnimatorControllerLayer{name=sm.name,stateMachine=sm,defaultWeight=1});
        if(!fx.parameters.Any(p=>p.name==ToggleParameter))fx.AddParameter(new AnimatorControllerParameter{name=ToggleParameter,type=AnimatorControllerParameterType.Bool,defaultBool=s.defaultOn});
        {
            var machine=new AnimatorStateMachine{name="ALO Outline Visibility"};
            var visible=machine.AddState("Visible");visible.motion=visibleClip;visible.writeDefaultValues=true;
            var hidden=machine.AddState("Hidden");hidden.motion=hiddenClip;hidden.writeDefaultValues=true;machine.defaultState=s.defaultOn?visible:hidden;
            var off=visible.AddTransition(hidden);off.duration=0;off.hasExitTime=false;off.AddCondition(AnimatorConditionMode.IfNot,0,ToggleParameter);
            var on=hidden.AddTransition(visible);on.duration=0;on.hasExitTime=false;on.AddCondition(AnimatorConditionMode.If,0,ToggleParameter);
            fx.AddLayer(new AnimatorControllerLayer{name=machine.name,stateMachine=machine,defaultWeight=1});
        }
        if(!fx.parameters.Any(p=>p.name==ModeParameter))fx.AddParameter(new AnimatorControllerParameter{name=ModeParameter,type=AnimatorControllerParameterType.Bool,defaultBool=s.defaultBreathing});
        {
            var machine=new AnimatorStateMachine{name="ALO Outline Mode"};var automatic=machine.AddState("Automatic audio");automatic.motion=autoMode;var breathing=machine.AddState("Fixed breathing");breathing.motion=breathMode;machine.defaultState=s.defaultBreathing?breathing:automatic;
            var force=automatic.AddTransition(breathing);force.duration=0;force.hasExitTime=false;force.AddCondition(AnimatorConditionMode.If,0,ModeParameter);
            var auto=breathing.AddTransition(automatic);auto.duration=0;auto.hasExitTime=false;auto.AddCondition(AnimatorConditionMode.IfNot,0,ModeParameter);
            fx.AddLayer(new AnimatorControllerLayer{name=machine.name,stateMachine=machine,defaultWeight=1});
        }
        foreach(var layer in fx.layers.Where(l=>l.name.StartsWith("ALO Outline ")))
            foreach(var state in States(layer.stateMachine))state.writeDefaultValues=writeDefaults;
        Debug.Log("audiolink outline lite added "+added+" triangles, "+memory+" mesh bytes, no new textures; world depth enabled.");
    }
    public static void ApplySettings(Material material,AudioLinkOutlineLiteSettings settings)
    {
        material.SetFloat("_ALOBrightness",settings.brightness);material.SetFloat("_ALOWidth",settings.width);
        material.SetFloat("_ALOWaveWidth",settings.waveWidth);material.SetFloat("_ALOHue",settings.hue);
        material.SetFloat("_ALOBreath",settings.defaultBreathing?1:0);material.SetFloat("_ALOBreathLength",settings.breathLength);material.SetFloat("_ALOBreathFrequency",settings.breathFrequency);
        material.SetFloat("_ALOOffsetHorizontal",settings.offset.x);material.SetFloat("_ALOOffsetVertical",settings.offset.y);
    }
    static IEnumerable<AnimatorState> States(AnimatorStateMachine machine)
    {foreach(var state in machine.states)yield return state.state;foreach(var child in machine.stateMachines)foreach(var state in States(child.stateMachine))yield return state;}
    static void CloneMotions(AnimatorStateMachine m,Dictionary<Motion,Motion> cache){foreach(var child in m.states)child.state.motion=Copy(child.state.motion,cache);foreach(var child in m.stateMachines)CloneMotions(child.stateMachine,cache);}
    static Motion Copy(Motion source,Dictionary<Motion,Motion> cache)
    {
        if(!source)return null;if(cache.TryGetValue(source,out var existing))return existing;
        var result=UnityEngine.Object.Instantiate(source);cache[source]=result;
        if(result is BlendTree t){var children=t.children;for(int i=0;i<children.Length;i++)children[i].motion=Copy(children[i].motion,cache);t.children=children;}return result;
    }
    static Material Guard(Material source,Dictionary<Material,Material> cache,int stencil)
    {
        if(!source||!source.shader.name.ToLowerInvariant().Contains("liltoon")||!source.HasProperty("_StencilRef"))return source;if(cache.TryGetValue(source,out var m))return m;
        m=new Material(source){name=source.name+" [Outline Guard]"};cache[source]=m;
        foreach(string prefix in new[]{"_Stencil","_OutlineStencil","_PreStencil"})
        {
            if(!m.HasProperty(prefix+"Ref"))continue;
            int reference=m.GetInt(prefix+"Ref"),read=m.GetInt(prefix+"ReadMask"),write=m.GetInt(prefix+"WriteMask"),pass=m.GetInt(prefix+"Pass");
            if((AudioLinkOutlineLiteStencil.ReservedBits(source)&stencil)!=0)throw new Exception("音律轮廓遮罩位分配发生冲突："+source.name);
            m.SetInt(prefix+"ReadMask",read&~stencil);m.SetInt(prefix+"WriteMask",write&~stencil);
            // Transparent prepasses must ignore the reserved bit too, but do not
            // mark their pixels as an opaque avatar silhouette.
            if(prefix=="_PreStencil")continue;
            bool faceMaskedHair=reference==47&&m.GetInt(prefix+"Comp")==3;
            if((!source.shader.name.Contains("Transparent")||faceMaskedHair)&&(pass==0||pass==2)&&m.GetInt(prefix+"Fail")==0&&m.GetInt(prefix+"ZFail")==0)
            {m.SetInt(prefix+"Ref",reference|stencil);m.SetInt(prefix+"WriteMask",pass==0?stencil:write|stencil);m.SetInt(prefix+"Pass",2);}
            else if(!source.shader.name.Contains("Transparent")&&pass==1&&reference==47&&m.GetInt(prefix+"Comp")==6)
            {
                // SeeThroughHair's opaque branch draws only outside its 47 mask.
                // The original successful branch normally clears an already-zero
                // low mask. Keep those low bits and mark only the silhouette bit;
                // comparing still ignores the allocated bit, so its translucent branch is unchanged.
                m.SetInt(prefix+"Ref",reference|stencil);m.SetInt(prefix+"WriteMask",stencil);m.SetInt(prefix+"Pass",2);
            }
        }
        return m;
    }
